package desc

import "testing"

func TestHIDKind(t *testing.T) {
	cases := map[string][]byte{
		// A DualSense-style gamepad: Generic Desktop, Gamepad.
		"Game controller": {0x05, 0x01, 0x09, 0x05, 0xa1, 0x01, 0x85, 0x01, 0x09, 0x30, 0x81, 0x02, 0xc0},
		// A wheel reporting as a joystick, with a second collection.
		"Keyboard": {0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x81, 0x02, 0xc0},
		"Mouse":    {0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x09, 0x01, 0xa1, 0x00, 0x09, 0x30, 0x81, 0x06, 0xc0, 0xc0},
		// Volume buttons of a headset or sound card: consumer controls only.
		"": {0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01, 0x09, 0xe9, 0x81, 0x02, 0xc0},
		// Unifying-style receiver: keyboard and mouse collections.
		"Keyboard and mouse": {0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0xc0, 0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0xc0},
	}
	for want, rd := range cases {
		if got := HIDKind(rd); got != want {
			t.Errorf("want %q, got %q", want, got)
		}
	}
	// Wheels and pedals: joystick usage, or the simulation-controls page.
	if HIDKind([]byte{0x05, 0x01, 0x09, 0x04, 0xa1, 0x01, 0xc0}) != "Game controller" ||
		HIDKind([]byte{0x05, 0x02, 0x09, 0xc8, 0xa1, 0x01, 0xc0}) != "Game controller" {
		t.Error("wheel or pedals not recognised")
	}
	// Garbage must not panic.
	HIDKind([]byte{0xfe, 0xff})
	HIDKind([]byte{0x07, 0x01})
}

func TestHIDRelease(t *testing.T) {
	// A keyboard's second interface: numbered reports, keyboard + media keys.
	nkro := []byte{0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x85, 0x01, 0xc0, 0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01, 0x85, 0x02, 0xc0}
	if r, ids := HIDRelease(nkro); !r || !ids {
		t.Fatalf("keyboard interface: %v %v", r, ids)
	}
	if r, ids := HIDRelease([]byte{0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0xc0}); !r || ids {
		t.Fatalf("plain keyboard: %v %v", r, ids)
	}
	if r, _ := HIDRelease([]byte{0x05, 0x01, 0x09, 0x05, 0xa1, 0x01, 0x85, 0x01, 0xc0}); r {
		t.Fatal("a gamepad must not be sent zeros")
	}
	if r, _ := HIDRelease([]byte{0x06, 0x00, 0xff, 0x09, 0x01, 0xa1, 0x01, 0xc0}); r {
		t.Fatal("a vendor interface must not be sent zeros")
	}
}
